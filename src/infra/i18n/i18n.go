func T(key string, args ...any) string {
	languageMu.RLock()
	currentLanguage := language
	languageMu.RUnlock()
	template, ok := messages[key]
	if currentLanguage == "vi" {
		template, ok = vietnameseMessages[key]
	}
	if !ok {
		template = key
	}
	if len(args) == 0 {
		return template
	}
	return fmt.Sprintf(template, args...)
}

func SetLanguage(value string) {
	languageMu.Lock()
	language = value
	languageMu.Unlock()
}

func Language() string {
	languageMu.RLock()
	defer languageMu.RUnlock()
	return language
}
